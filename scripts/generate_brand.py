from pathlib import Path
import re,sys,json
root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root/'.local'/'brand-tools'))
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen



palette=dict(re.findall(r'--brand-([a-z-]+):(#[0-9a-fA-F]{3,6})(?:;|})',(root/'src/brand/brand.css').read_text()))
(root/'src/brand/palette.ts').write_text('// Generated from brand.css by scripts/generate_brand.py. Do not hand edit.\nexport const brandPalette='+json.dumps(palette,indent=2)+' as const;\n')
destination=root/'public'/'brand'
destination.mkdir(parents=True,exist_ok=True)
paths=re.findall(r"  '(M[^']+)'",(root/'src/brand/BrandMark.tsx').read_text())
assert len(paths)==2
mark=''.join(f'<path d="{p}"/>' for p in paths)
font=instantiateVariableFont(TTFont(str(root/'node_modules/@fontsource-variable/geist/files/geist-latin-wght-normal.woff2')),{'wght':650},inplace=True)
glyphs=font.getGlyphSet();cmap=font.getBestCmap();scale=44/font['head'].unitsPerEm
x=56;letters=[];letter_paths=[]
for char in 'plansaathi':
    name=cmap[ord(char)];pen=SVGPathPen(glyphs)
    glyphs[name].draw(TransformPen(pen,(scale,0,0,-scale,x,38)))
    letter_paths.append(pen.getCommands())
    letters.append(f'<path d="{pen.getCommands()}"/>')
    x+=(font['hmtx'][name][0]-font['head'].unitsPerEm*.028)*scale
word=''.join(letters);width=round(x+1,2)
(root/'src/brand/wordmark.ts').write_text('// Generated by scripts/generate_brand.py.\nexport const WORDMARK_WIDTH='+str(width)+';\nexport const WORDMARK_PATHS='+json.dumps(letter_paths)+';\n',encoding='utf-8')
for name,icon_color,type_color in [('plansaathi-lockup',palette['primary'],palette['ink']),('plansaathi-lockup-mono',palette['ink'],palette['ink']),('plansaathi-lockup-reversed',palette['surface'],palette['surface'])]:
    (destination/f'{name}.svg').write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} 48" role="img" aria-label="PlanSaathi"><title>PlanSaathi</title><g fill="{icon_color}">{mark}</g><g fill="{type_color}">{word}</g></svg>')
for name,color in [('plansaathi-mark',palette['primary']),('plansaathi-mark-mono',palette['ink']),('plansaathi-mark-reversed',palette['surface'])]:
    (destination/f'{name}.svg').write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" fill="{color}" role="img" aria-label="PlanSaathi"><title>PlanSaathi</title>{mark}</svg>')
(root/'src/app/icon.svg').write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 56 56"><rect width="56" height="56" rx="14" fill="{palette["primary"]}"/><g transform="translate(4 4)" fill="white">{mark}</g></svg>')
board=f'''<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="760" viewBox="0 0 1200 760">
<rect width="1200" height="760" fill="#f7f8fc"/><g font-family="Arial,sans-serif" fill="#62677b" font-size="13" letter-spacing="2"><text x="64" y="55">PLANSAATHI / VISUAL IDENTITY</text><text x="1000" y="55">CONCEPT 02</text></g>
<g transform="translate(190 160) scale(3.05)" fill="#3c49eb">{mark}</g><g transform="translate(465 200) scale(1.65)"><g fill="#3c49eb">{mark}</g><g fill="#171a2b">{word}</g></g>
<path d="M64 384H1136" stroke="#e4e7f0"/><rect x="64" y="430" width="328" height="200" rx="18" fill="#3c49eb"/><g transform="translate(188 490) scale(1.7)" fill="#ffffff">{mark}</g>
<rect x="416" y="430" width="328" height="200" rx="18" fill="#171a2b"/><g transform="translate(540 490) scale(1.7)" fill="#ffffff">{mark}</g>
<rect x="768" y="430" width="368" height="200" rx="18" fill="#eef0ff"/><g transform="translate(854 491) scale(.9)"><g fill="#3c49eb">{mark}</g><g fill="#171a2b">{word}</g></g>
<g font-family="Arial,sans-serif" fill="#62677b" font-size="14"><text x="64" y="675">Two open room corners. A shared space.</text><text x="64" y="705">Cobalt / Ink / Clear white</text><text x="768" y="675">Vector mark + outlined wordmark</text><text x="768" y="705">Geist 650 · optical letter spacing</text></g></svg>'''
(destination/'plansaathi-identity.svg').write_text(board,encoding='utf-8')
import xml.etree.ElementTree as ET
for asset in destination.glob('*.svg'):
    ET.parse(asset)
print(f'Generated 7 portable SVG brand assets; lockup width {width}.')
